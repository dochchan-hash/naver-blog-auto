const template=createRequire(import.meta.url)('../server/construction/public/cover-template.js');

test('공사 표지 원본 배치와 두 종류를 유지하고 수정값·문구를 검증한다',async()=>{
  const before=template.settings('before'),during=template.settings('during');
  assert.equal(before.badgeText,'공사전');assert.equal(during.badgeText,'공사중');assert.equal(before.badgeColor,'#FFAF26');assert.equal(during.badgeColor,'#D66F31');
  assert.deepEqual(template.frame,{left:396,top:566,width:2206,height:1996});assert.equal(before.saturation,20);assert.equal(before.titleSize,122);
  const center=template.placement(2206,1996,before),moved=template.placement(2206,1996,{...before,x:0,y:0});
  assert.equal(center.x,0);assert.equal(center.y,0);assert(moved.x>0&&moved.y>0);
  for(const change of [{zoom:20},{x:NaN},{titleColor:'red;display:none'},{titleFont:"x';color:red"},{titleAlign:'justify'},{badgeVisible:'false'},{titleText:'x\n<script>'}])assert.throws(()=>template.normalize(change));
  const html=template.markup({cover:template.settings('before',{titleText:'<script>bad()</script>'})});assert(!html.includes('<script>'));assert(html.includes('&lt;script&gt;'));
  const source=await fs.readFile('server/construction/public/cafe.html','utf8');for(const script of source.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))new vm.Script(script[1].replace('__LEMON_CSRF__','"test"'));
});

test('두 공사 표지를 화면에서 수정·수동 적용·다운로드하고 실패 때 기존 JPG를 보존한다',{timeout:90000},async t=>{
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'.studio-cover-'));
  await fs.mkdir(path.join(dir,'construction'),{recursive:true});await fs.writeFile(path.join(dir,'construction/cafe.config.json'),JSON.stringify({cafeId:'123456'}));
  const runtime=await createServer({dataDir:dir,port:0}),api=await localApi(runtime.url),browser=await chromium.launch({channel:'chrome',headless:true});
  t.after(async()=>{await browser.close();await runtime.close();await fs.rm(dir,{recursive:true,force:true});});
  const page=await browser.newPage({viewport:{width:1280,height:1000}}),errors=[];page.on('pageerror',error=>errors.push(error.message));
  const image=await sharp({create:{width:600,height:400,channels:3,background:'#557799'}}).jpeg().toBuffer();
  let renders=0;page.on('request',req=>{if(req.method()==='POST'&&/\/cover$/.test(req.url()))renders++;});
  for(const kind of ['before','during']){
    const form=new FormData();for(const [key,value]of Object.entries({kind,sido:'서울',gu:'마포구',apt:'표지 테스트'}))form.append(key,value);form.append('photos',new Blob([image],{type:'image/jpeg'}),'원본.jpg');
    const {id}=await api.request('/cafe/jobs','POST',form);
    await page.goto(runtime.url+'/construction?kind='+kind);
    assert.equal(await page.locator('input[name=kind],input[name=jkind]').count(),0);
    assert.equal(await page.locator('h1').textContent(),(kind==='before'?'공사전':'공사중')+' 작성 · 카페');
    await page.locator('.list-item[data-id="'+id+'"]').click();await page.locator('#coverStage .artboard').waitFor();
    assert(await page.locator('#coverCard').isVisible());assert.equal(await page.locator('#jGen').count(),1);
    const coverBefore=(await api.request('/cafe/jobs/'+id)).cover;
    assert.equal((await api.request('/cafe/jobs/'+id)).coverLogo,true);
    const logo=await page.request.get(runtime.url+'/api/cafe/cover-logo/'+kind);assert.equal(logo.status(),200);
    assert.deepEqual(await logo.body(),await fs.readFile('server/construction/public/brand/logo-'+kind+'.png'));
    await page.locator('#coverStage .logo').waitFor();
    await page.locator('#coverTitleControls').evaluate(el=>el.open=true);await page.locator('#coverTitleAuto').uncheck();await page.locator('#cv-titleText').fill('수정한 '+kind+' 표지');
    await page.locator('#cv-x').fill('15');await page.locator('#cv-x').dispatchEvent('input');
    await page.locator('#coverBadgeControls').evaluate(el=>el.open=true);await page.locator('#cv-badgeText').fill('확인');
    assert.equal(await page.locator('#coverStage .title span').textContent(),'수정한 '+kind+' 표지');assert.equal(await page.locator('#coverStage .badge').textContent(),'확인');
    assert.deepEqual((await api.request('/cafe/jobs/'+id)).cover,coverBefore);assert.equal(renders,kind==='before'?0:1);
    const applied=page.waitForResponse(res=>/\/cover$/.test(res.url())&&res.request().method()==='POST');await page.locator('#coverApply').click();assert.equal((await applied).status(),200);
    await page.waitForFunction(()=>document.querySelector('#coverStatus').textContent.includes('카페 표지로'));
    await page.locator('#coverApplied').evaluate(el=>el.open=true);await page.locator('#coverImg').waitFor();assert.match(await page.locator('#coverImg').getAttribute('src'),/cover\.jpg\?t=/);
    const saved=await api.request('/cafe/jobs/'+id);assert.equal(saved.cover.titleText,'수정한 '+kind+' 표지');assert.equal(saved.cover.x,15);assert.equal(saved.cover.made,true);
    const coverFile=path.join(dir,'construction/data/jobs',id,'cover.jpg'),jpg=await fs.readFile(coverFile),meta=await sharp(jpg).metadata();assert.equal(meta.width,3000);assert.equal(meta.height,3000);
    const pixels=await sharp(jpg).extract({left:1185,top:2643,width:638,height:131}).removeAlpha().raw().toBuffer();let colored=0;
    for(let i=0;i<pixels.length;i+=3)if(pixels[i]>180&&pixels[i+1]<220&&pixels[i+2]<100)colored++;
    assert(colored>10000,'하단 JPG에 원본 로고가 있어야 합니다.');
    assert.deepEqual(await fs.readFile(path.join(dir,'construction/data/jobs',id,'photos/원본.jpg')),image);
    const download=await page.request.get(runtime.url+'/api/cafe/jobs/'+id+'/cover.jpg?download=1');
    assert.match(download.headers()['content-disposition'],/attachment/);assert.deepEqual(await download.body(),jpg);
    await api.request('/cafe/jobs/'+id,'PUT',{draft:{intro:'인사',sections:[{photos:['원본.jpg'],text:'현장 설명'}],outro:'마무리'}});
    const reopened=await api.request('/cafe/jobs/'+id);assert(reopened.blocks.some(b=>b.t==='cover'));
    await page.reload();
    await page.locator('.list-item[data-id="'+id+'"]').click();await page.locator('#coverStage .artboard').waitFor();
    assert.equal(await page.locator('#coverStage .title span').textContent(),saved.cover.titleText);
    const uploading=page.waitForResponse(res=>/\/cover-photo$/.test(res.url())&&res.request().method()==='POST');
    await page.locator('#coverFile').setInputFiles({name:'추가 사진.jpg',mimeType:'image/jpeg',buffer:image});assert.equal((await uploading).status(),200);
    await page.waitForFunction(()=>document.querySelector('#coverStatus').textContent.includes('미적용'));
    assert.deepEqual((await api.request('/cafe/jobs/'+id)).cover,saved.cover);
    await page.locator('#coverCancel').click();
    const dropped=await page.evaluateHandle(()=>{const transfer=new DataTransfer();transfer.setData('application/x-lemon-construction-photo','추가 사진.jpg');return transfer;});
    await page.locator('#coverStage').dispatchEvent('drop',{dataTransfer:dropped});
    assert.equal(await page.locator('#coverPick [aria-pressed=true]').getAttribute('data-n'),'추가 사진.jpg');
    await page.locator('#coverCancel').click();
    assert.equal(await page.locator('#coverPick [aria-pressed=true]').getAttribute('data-n'),'원본.jpg');
    for(const edit of [{photo:'../다른.jpg'},{photo:'원본.jpg',zoom:100},{photo:'원본.jpg',badgeColor:'bad'}])await assert.rejects(api.request('/cafe/jobs/'+id+'/cover','POST',edit));
    const broken=new FormData();broken.append('photo',new Blob(['invalid image'],{type:'image/jpeg'}),'손상.jpg');await api.request('/cafe/jobs/'+id+'/cover-photo','POST',broken);
    assert.deepEqual((await api.request('/cafe/jobs/'+id)).cover,saved.cover);
    await assert.rejects(api.request('/cafe/jobs/'+id+'/cover','POST',{photo:'손상.jpg',titleText:'실패 시 저장 안 함'}));
    assert.deepEqual((await api.request('/cafe/jobs/'+id)).cover,saved.cover);assert.deepEqual(await fs.readFile(coverFile),jpg);
    await assert.rejects(api.request('/cafe/jobs/'+id,'PUT',{분류:kind==='before'?'during':'before'}),/공사 종류는 변경할 수 없습니다/);
    assert.equal((await api.request('/cafe/jobs/'+id)).분류,kind);
  }
  await page.goto(runtime.url);
  await page.getByRole('button',{name:'공사중 작성 · 카페',exact:true}).click();
  const editor=page.frameLocator('iframe[title="공사중 작성 화면"]');
  const before=page.frameLocator('iframe[title="공사전 작성 화면"]');
  await editor.locator('h1').filter({hasText:'공사중 작성'}).waitFor();
  assert.equal(await page.locator('iframe[title="공사중 작성 화면"]').getAttribute('src'),'/construction?kind=during');
  assert.equal(await editor.locator('.list-item').count(),1);
  await page.getByRole('button',{name:'새 공사중 작성',exact:true}).click();
  await editor.locator('#v-new').waitFor({state:'visible'});await editor.locator('#f-memo').fill('공사중 전용 메모');
  await editor.locator('#f-photos').setInputFiles({name:'공사중 사진.jpg',mimeType:'image/jpeg',buffer:image});
  await page.getByRole('button',{name:'공사전 작성 · 카페',exact:true}).click();await before.locator('h1').filter({hasText:'공사전 작성'}).waitFor();
  await page.getByRole('button',{name:'새 공사전 작성',exact:true}).click();await before.locator('#v-new').waitFor({state:'visible'});
  assert.equal(await before.locator('#newKindHeading').textContent(),'1. 공사전 현장 정보');assert.equal(await before.locator('#f-memo').inputValue(),'');
  assert.equal(await before.locator('#photoPrev .thumb').count(),0);await before.locator('#f-memo').fill('공사전 전용 메모');
  await page.getByRole('button',{name:'공사중 작성 · 카페',exact:true}).click();await editor.locator('h1').filter({hasText:'공사중 작성'}).waitFor();
  await page.getByRole('button',{name:'새 공사중 작성',exact:true}).click();await editor.locator('#v-new').waitFor({state:'visible'});
  assert.equal(await editor.locator('#f-memo').inputValue(),'공사중 전용 메모');assert.equal(await editor.locator('#photoPrev .nm').textContent(),'공사중 사진.jpg');
  assert.equal(await editor.locator('input[name=kind],input[name=jkind]').count(),0);
  assert.deepEqual(errors,[]);assert.equal((await api.request('/bootstrap')).projects.length,1);
});
